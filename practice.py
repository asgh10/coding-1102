name = "현빈1"
print(name.isalpha())
# 문자열로만 이루어 져있는지 확인하는 코드  숫자나 특수기호가 있을 시 false 반환

#-----------------------------------------------------------------------------------

number = "123"
print(number.isdigit())
# 숫자로 이루어져 있는지 확인하는 코드 문자열이나 특수기호가 있을 시 false 반환
# 알아둘 점: isdigit()이 숫자로 인정하는 문자의 범위가 일반적인 정수 변환보다 넓다

#-----------------------------------------------------------------------------------


str_num = "hi 123"
print(str_num.isalnum())
# 문자 또는 숫자로만 이루어져 있는지 확인하는 코드 
# 중요한 점: 공백도 허용하지 않음

# -----------------------------------------------------------------------------------

# 일반적인 for 문의 형식
name = "현빈"

for char in name:
    print(char.isalpha())



# 전에 사용한 제너레이터 라고 불리는 형식
name = "현빈"

(char.isalpha() for char in name)

